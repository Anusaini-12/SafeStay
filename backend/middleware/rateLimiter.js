import rateLimit from "express-rate-limit";

export const searchRateLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  limit: 20,
  standardHeaders: "draft-8",
  legacyHeaders: false,
  message: {
    error: "Too many search requests. Please try again later.",
  },
});

